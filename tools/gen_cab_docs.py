"""Generate docs/cabs.md from the packaged cab YAMLs and docs/cab_notes.yml.

Usage:
    uv run python tools/gen_cab_docs.py
    uv run python tools/gen_cab_docs.py --check

The packaged YAMLs remain the single source of truth for cab names, images,
commands and the flattened parameter schemas.  ``docs/cab_notes.yml`` supplies
the purpose, usage notes and examples that a schema cannot describe.
"""

from __future__ import annotations

import argparse
import difflib
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from scabha.basetypes import UNSET
from scabha.cargo import Cargo, Parameter

ROOT = Path(__file__).resolve().parents[1]
CAB_DIR = ROOT / "dde_cargo"
NOTES_FILE = ROOT / "docs" / "cab_notes.yml"
OUTPUT_FILE = ROOT / "docs" / "cabs.md"
CAB_FILES = (
    "ddfacet.yml",
    "ddfacet-memory-plan.yml",
    "killms-memory-plan.yml",
    "pick-reference-ant.yml",
)

GENERATED_MARKER = "<!-- Generated by tools/gen_cab_docs.py; do not edit by hand. -->"


@dataclass
class CabDoc:
    name: str
    cab: dict[str, Any]
    notes: dict[str, Any]
    image: str
    kind: str
    inputs: dict[str, Parameter]
    outputs: dict[str, Parameter]


def _read_yaml(path: Path) -> Any:
    try:
        return yaml.safe_load(path.read_text())
    except (OSError, yaml.YAMLError) as exc:
        raise RuntimeError(f"cannot read {path}: {exc}") from exc


def _merge_inputs(cab: dict[str, Any], cab_path: Path) -> dict[str, Any]:
    """Merge a cab's direct inputs with its `_include`d schema."""
    raw = cab.get("inputs") or {}
    include = raw.get("_include")
    merged: dict[str, Any] = {}
    if include:
        includes = include if isinstance(include, list) else [include]
        for name in includes:
            schema_path = cab_path.parent / str(name)
            merged.update(_read_yaml(schema_path))
    merged.update({key: value for key, value in raw.items() if key != "_include"})
    return merged


def _flatten(mapping: dict[str, Any], label: str) -> dict[str, Parameter]:
    try:
        flat: dict[str, Parameter] = {}
        Cargo.flatten_schemas(flat, mapping, label=label)
        return flat
    except Exception as exc:
        raise RuntimeError(f"cannot flatten {label}: {exc}") from exc


def _merge_docs(base: dict[str, Any], extra: dict[str, Any]) -> dict[str, Any]:
    """Merge two documents into a new dict (later files win on scalar
    collisions); the inputs are left untouched."""
    merged = dict(base)
    for key, value in extra.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _merge_docs(merged[key], value)
        else:
            merged[key] = value
    return merged


def _resolve_image(cab: dict[str, Any], doc: dict[str, Any]) -> str:
    """Resolve both image shapes used by the cabs (`_use` vars + name)."""
    raw = cab.get("image")
    if not isinstance(raw, dict):
        raise RuntimeError(f"cab {cab.get('name', '?')}: no image definition")
    image = {key: value for key, value in raw.items() if key != "_use"}
    use = raw.get("_use")
    if use:
        base: Any = doc
        for part in str(use).split("."):
            try:
                base = base[part]
            except (KeyError, TypeError) as exc:
                raise RuntimeError(f"cannot resolve image var {use!r}") from exc
        if not isinstance(base, dict):
            raise RuntimeError(f"image var {use!r} is not a mapping")
        for key, value in base.items():
            image.setdefault(key, value)

    registry = str(image.get("registry", "")).rstrip("/")
    name = str(image.get("name", ""))
    version = image.get("version")
    if not registry or not name:
        raise RuntimeError(f"incomplete image definition: {raw}")
    return f"{registry}/{name}" + (f":{version}" if version else "")


def _kind(cab: dict[str, Any]) -> str:
    if set(cab) - {"name"} == {"image"}:
        return "image override"
    if "memory-plan" in str(cab.get("name", "")):
        return "memory plan"
    flavour = cab.get("flavour")
    if isinstance(flavour, dict) and flavour.get("kind") == "python-code":
        return "python-code"
    return "container"


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _cell(text: Any) -> str:
    """Make a value safe inside a Markdown table cell."""
    value = "" if text is None else str(text)
    value = re.sub(r"\s*\n\s*", "<br>", value.strip())
    return value.replace("|", r"\|")


def _default(param: Parameter, cab: dict[str, Any], name: str) -> str:
    defaults = cab.get("defaults") or {}
    value = defaults.get(name, param.default)
    if value is UNSET or value is None:
        return "—"
    if isinstance(value, bool):
        return f"`{str(value)}`"
    if isinstance(value, (list, tuple)):
        return f"`{value}`"
    return f"`{value}`"


def _description(param: Parameter, notes: dict[str, Any], name: str) -> str:
    text = param.info or (notes.get("parameter_info") or {}).get(name, "")
    extras = []
    if param.implicit:
        extras.append(f"Implicit: `{param.implicit}`")
    if param.choices:
        extras.append("Choices: " + ", ".join(f"`{choice}`" for choice in param.choices))
    if extras:
        text = (text + " " if text else "") + " ".join(extras)
    return text


def _parameter_table(
    names: list[str],
    params: dict[str, Parameter],
    cab: dict[str, Any],
    notes: dict[str, Any],
) -> list[str]:
    lines = [
        "| Parameter | Type | Required | Default | Description |",
        "|---|---|---|---|---|",
    ]
    for name in names:
        param = params[name]
        required = "yes" if param.required else "no"
        lines.append(
            f"| `{name}` | `{param.dtype}` | {required} | "
            f"{_default(param, cab, name)} | {_cell(_description(param, notes, name))} |"
        )
    return lines


def _output_table(outputs: dict[str, Parameter]) -> list[str]:
    lines = [
        "| Output | Type | Required | Implicit |",
        "|---|---|---|---|",
    ]
    for name, param in outputs.items():
        required = "yes" if param.required else "no"
        implicit = f"`{param.implicit}`" if param.implicit else "—"
        lines.append(f"| `{name}` | `{param.dtype}` | {required} | {implicit} |")
    return lines


def _grouped_inputs(
    cab: CabDoc,
) -> list[tuple[str, list[str]]]:
    """Return ordered (group title, parameter names) pairs."""
    notes = cab.notes
    if cab.name == "killms":
        groups: list[tuple[str, list[str]]] = []
        seen: set[str] = set()
        for title, names in (notes.get("groups") or {}).items():
            selected = [name for name in names if name in cab.inputs]
            if selected:
                groups.append((str(title), selected))
                seen.update(selected)
        other = sorted(set(cab.inputs) - seen)
        if other:
            groups.append(("Other parameters", other))
        return groups

    if cab.name == "ddfacet":
        groups: list[tuple[str, list[str]]] = []
        by_namespace: dict[str, list[str]] = {}
        for name in cab.inputs:
            namespace = name.split(".", 1)[0]
            by_namespace.setdefault(namespace, []).append(name)
        groups.extend(by_namespace.items())
        return groups

    return [("Inputs", list(cab.inputs))]


def _render_cab(cab: CabDoc) -> list[str]:
    anchor = f'<a id="cab-{_slug(cab.name)}"></a>'
    lines = [anchor, f"## `{cab.name}`", ""]
    lines.append(f"**Purpose:** {cab.notes.get('purpose', '').strip()}")
    lines.append("")
    lines.append(f"**Kind:** {cab.kind}  ")
    lines.append(f"**Image:** `{cab.image}`  ")
    command = cab.cab.get("command")
    if command and cab.kind == "container":
        first_line = str(command).strip().splitlines()[0]
        lines.append(f"**Command:** `{first_line}`  ")
    elif command:
        lines.append("**Command:** inline Python  ")
    lines.append("")

    info = (cab.cab.get("info") or "").strip()
    if info:
        lines += ["### Description", "", info, ""]

    notes = (cab.notes.get("notes") or "").strip()
    if notes:
        lines += ["### Notes", "", notes, ""]

    if cab.inputs:
        lines += ["### Inputs", ""]
        for title, names in _grouped_inputs(cab):
            namespace_info = (cab.notes.get("namespace_info") or {}).get(title, "")
            summary = f"<code>{title}</code> ({len(names)} parameters)"
            lines += ["<details>", f"<summary>{summary}</summary>", ""]
            if namespace_info:
                lines += [f"*{namespace_info.strip()}*", ""]
            lines += _parameter_table(names, cab.inputs, cab.cab, cab.notes)
            lines += ["", "</details>", ""]
    else:
        lines += ["### Inputs", "", "This cab defines no inputs.", ""]

    if cab.outputs:
        lines += ["### Outputs", "", *_output_table(cab.outputs), ""]
    else:
        lines += ["### Outputs", "", "This cab defines no outputs.", ""]

    example = (cab.notes.get("example") or "").strip()
    if example:
        lines += ["### Example", "", "```yaml", example, "```", ""]

    return lines


def _render(docs: list[CabDoc]) -> str:
    lines = [
        GENERATED_MARKER,
        "",
        "# Cab reference",
        "",
        "This reference is generated from the packaged cab YAMLs and",
        "[`docs/cab_notes.yml`](cab_notes.yml).  The YAMLs are the source of truth",
        "for names, images, commands and parameter schemas; the notes file supplies",
        "the purpose, usage guidance and examples.",
        "",
        "Regenerate with `invoke docs` or `uv run python tools/gen_cab_docs.py`.",
        "",
        "Parameter names below are the exact keys to use under `params:` in a",
        "stimela recipe.  DDFacet parameters are nested parset namespaces",
        "(`Data.MS` becomes `--Data-MS`); killMS parameters are flat flags passed",
        "through `kMS.py`.",
        "",
        "## Contents",
        "",
        "- [At a glance](#at-a-glance)",
        "- [Typical wiring](#typical-wiring)",
    ]
    for doc in docs:
        lines.append(f"- [`{doc.name}`](#cab-{_slug(doc.name)})")
    lines += [
        "",
        "## At a glance",
        "",
        "| Cab | Kind | Purpose | Image |",
        "|---|---|---|---|",
    ]
    for doc in docs:
        lines.append(
            f"| [`{doc.name}`](#cab-{_slug(doc.name)}) | {_cell(doc.kind)} | "
            f"{_cell(doc.notes.get('purpose', ''))} | `{doc.image}` |"
        )

    lines += [
        "",
        "## Typical wiring",
        "",
        "Only `ddfacet.yml` is essential.  The memory-plan cabs are optional and",
        "must be wired ahead of the step they plan.  `pick-reference-ant` must",
        "come after `ddfacet.yml` (its image resolves ddfacet.yml's",
        "`vars.tim-molteno.images`).  Include cult-cargo's `bdsf.yml` before",
        "`ddfacet.yml` because of the `bdsf.catalog` image override:",
        "",
        "```yaml",
        "_include:",
        "  - (cultcargo):",
        "      - bdsf.yml",
        "  - (dde_cargo):",
        "      - ddfacet.yml",
        "      - pick-reference-ant.yml",
        "      - ddfacet-memory-plan.yml",
        "      - killms-memory-plan.yml",
        "```",
        "",
        "A common DD loop is: DI image with `ddfacet` -> build the initial model",
        "(`ddf_makemodel`) or cluster a catalogue (`clustercat`) -> optional",
        "`modelcat`/`snapnodes` refinement -> solve with `killms` -> correct the",
        "image with another `ddfacet` run.  The mask helpers (`ddf_makemask`,",
        "`dilatemask`) sit beside the imaging steps, and `autofacet` can refine the",
        "facet layout from the DI products.  The order is illustrative; the",
        "recipe's own step flow controls what runs.",
        "",
    ]

    for doc in docs:
        lines += _render_cab(doc)
        lines += ["---", ""]

    return "\n".join(lines).rstrip() + "\n"


def build_docs() -> list[CabDoc]:
    notes = _read_yaml(NOTES_FILE)
    if not isinstance(notes, dict):
        raise RuntimeError(f"{NOTES_FILE}: expected a mapping keyed by cab name")

    docs_by_file = {filename: _read_yaml(CAB_DIR / filename) for filename in CAB_FILES}
    # stimela merges every included file into one document before resolving an
    # image's `_use`, so a cab without its own vars (pick-reference-ant, whose
    # image comes from ddfacet.yml's vars.tim-molteno.images) resolves against
    # the combined doc, not its own file
    combined: dict[str, Any] = {}
    for doc in docs_by_file.values():
        combined = _merge_docs(combined, doc)

    docs: list[CabDoc] = []
    seen: set[str] = set()
    for filename in CAB_FILES:
        cab_path = CAB_DIR / filename
        doc = docs_by_file[filename]
        for name, cab in (doc.get("cabs") or {}).items():
            if name in seen:
                raise RuntimeError(f"cab {name!r} is defined more than once")
            seen.add(name)
            if name not in notes:
                raise RuntimeError(
                    f"docs/cab_notes.yml has no entry for cab {name!r}; "
                    "add a purpose and notes before regenerating"
                )
            cab = {"name": name, **cab}
            docs.append(
                CabDoc(
                    name=name,
                    cab=cab,
                    notes=notes[name],
                    image=_resolve_image(cab, combined),
                    kind=_kind(cab),
                    inputs=_flatten(_merge_inputs(cab, cab_path), f"{name}.inputs"),
                    outputs=_flatten(cab.get("outputs") or {}, f"{name}.outputs"),
                )
            )

    unknown = set(notes) - seen
    if unknown:
        raise RuntimeError(
            "docs/cab_notes.yml has entries for unknown cabs: "
            + ", ".join(sorted(unknown))
        )
    return docs


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, path)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if docs/cabs.md is not current; do not write",
    )
    args = parser.parse_args(argv)

    try:
        text = _render(build_docs())
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.check:
        if not OUTPUT_FILE.exists():
            print(f"error: {OUTPUT_FILE} does not exist", file=sys.stderr)
            return 1
        current = OUTPUT_FILE.read_text()
        if current == text:
            print(f"{OUTPUT_FILE} is current")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(),
            text.splitlines(),
            fromfile=str(OUTPUT_FILE),
            tofile="regenerated",
            lineterm="",
        )
        for line in list(diff)[:200]:
            print(line, file=sys.stderr)
        print(
            f"\nerror: {OUTPUT_FILE} is stale; run `invoke docs`",
            file=sys.stderr,
        )
        return 1

    _write_atomic(OUTPUT_FILE, text)
    print(f"wrote {OUTPUT_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
